# --- ???? ?????? ?????????? (Thresholds in Amperes) ---
IDLE_CURRENT_MAX = 0.05  # ??? ?? 0.05A ?????? ???? (Idle)
ABNORMAL_CURRENT_MAX = 4.0  # ?? 0.20A ??? 0.50A ?????? ??? ??? ?????
OVERLOAD_CRITICAL = 5.0  # ???? ?? 0.50A ?????? ??? ???? ???? (Overload)

# --- ??????? ???? ?????? ---
IDLE_TIMEOUT_SECONDS = 5

# --- ??????? I2C ????? INA219 ---
INA219_ADDRESS = 0x40  # ????? I2C ????????? ??????
REG_SHUNT_VOLTAGE = 0x01
REG_BUS_VOLTAGE = 0x02


def read_ina219(bus):
  """????? ????? ??????? ??????? ?? ???? INA219 ??? I2C"""
  try:
    # ????? ??? ??? ???????? ??????? (Shunt Voltage Register)
    raw_bytes = bus.read_i2c_block_data(INA219_ADDRESS, REG_SHUNT_VOLTAGE, 2)
    value = (raw_bytes[0] << 8) | raw_bytes[1]
    if value > 32767:
      value -= 65536

    # LSB = 10uV? ???????? ???????? = 0.1 Ohm
    shunt_voltage = value * 0.00001
    current = abs(shunt_voltage / 0.1)

    # ????? ??? ?????? (Bus Voltage)
    raw_bus = bus.read_i2c_block_data(INA219_ADDRESS, REG_BUS_VOLTAGE, 2)
    bus_val = (raw_bus[0] << 8) | raw_bus[1]
    voltage = (bus_val >> 3) * 0.004

    return voltage, current
  except Exception:
    return 0.0, 0.0


def set_indicators(green, yellow, red):
  """????? ???? ????? ??????"""
  GPIO.output(LED_GREEN, GPIO.HIGH if green else GPIO.LOW)
  GPIO.output(LED_YELLOW, GPIO.HIGH if yellow else GPIO.LOW)
  GPIO.output(LED_RED, GPIO.HIGH if red else GPIO.LOW)


def main():
  peripheral_setup()
  connect_mqtt()

  # ??? ???? I2C ?? ???????? ??? (I2C Bus 1)
  bus = smbus.SMBus(1)

  idle_start_time = None
  machine_active = True

  print("====================================================")
  print("  Smart Motor Control System (INA219 + HiveMQ)")
  print("====================================================")

  while 1:
    peripheral_loop()

    # 1. ????? ????? ??????? ?? INA219
    voltage, current = read_ina219(bus)

    # ??? ?? ????? ???????? ???? ????? ?????
    if not machine_active:
      print(f"[STOPPED] Machine OFF | Current: {current:.3f}A")
      time.sleep(1)
      continue

    # 2. ????? ???? ?????? ???????? ???????? (Cascade) ???? ????? ??????

    # ?. ???? ????? ?????? ?????? (Critical Overload)
    if current >= OVERLOAD_CRITICAL:
      status_str = "CRITICAL OVERLOAD"
      print(
          f"\n[ALERT - OVERLOAD] Critical Current: {current:.3f}A! Exceeds"
          f" Limit ({OVERLOAD_CRITICAL}A)"
      )
      print(
          "[ACTION] Emergency Shutdown Initiated to Protect Equipment!"
      )

      GPIO.output(RELAY_PIN, GPIO.LOW)
      set_indicators(green=False, yellow=False, red=True)
      machine_active = False

      publish_alert(
          "OVERLOAD_SHUTDOWN",
          f"Current {current:.3f}A exceeded critical threshold"
          f" {OVERLOAD_CRITICAL}A",
      )
      continue

    # ?. ???? ????? ??? ??????? (Abnormal Load)
    elif current >= ABNORMAL_CURRENT_MAX:
      status_str = "WARNING: Operating under Abnormal High Load"
      set_indicators(green=False, yellow=False, red=True)
      idle_start_time = None

    # ?. ???? ??????? ??????? (Normal Operation)
    elif current >= IDLE_CURRENT_MAX:
      status_str = "NORMAL: Operating under standard load"
      set_indicators(green=True, yellow=False, red=False)
      idle_start_time = None

    # ?. ???? ?????? (Idle)
    else:
      status_str = "IDLE: Running without significant load"
      set_indicators(green=False, yellow=True, red=False)

      if idle_start_time is None:
        idle_start_time = time.time()
      else:
        elapsed_idle = time.time() - idle_start_time
        status_str += (
            f" (Idle for {int(elapsed_idle)}s / {IDLE_TIMEOUT_SECONDS}s)"
        )

        if elapsed_idle >= IDLE_TIMEOUT_SECONDS:
          print(
              f"\n[IDLE SHUTDOWN] Machine Idle for {IDLE_TIMEOUT_SECONDS}"
              " seconds."
          )
          print(
              "[ACTION] Auto Shutdown executed to save energy & prevent wear."
          )

          GPIO.output(RELAY_PIN, GPIO.LOW)
          set_indicators(green=False, yellow=False, red=False)
          machine_active = False

          publish_alert(
              "IDLE_SHUTDOWN",
              f"Machine shut down automatically after {IDLE_TIMEOUT_SECONDS}s"
              " idle.",
          )
          continue

    # 3. ????? ???????? ???????? ??? MQTT
    telemetry_payload = {
        "voltage": round(voltage, 2),
        "current": round(current, 3),
        "status": status_str,
        "machine_active": machine_active,
    }
    mqtt_client.publish(MQTT_TOPIC_TELEMETRY, json.dumps(telemetry_payload))

    # ????? ??????? ?? ??? Console
    print(
        f"Volt: {voltage:.2f}V | Curr: {current:.3f}A | State: {status_str}"
    )

    time.sleep(0.5)


if __name__ == "__main__":
  main()
